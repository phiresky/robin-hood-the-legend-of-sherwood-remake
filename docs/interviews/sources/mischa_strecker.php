<td><p ID="normal">

<i>Die meisten werden die Antwort auf diese Frage bereits kennen, aber für die die es noch nicht wissen: Was ist deine Aufgabe bei Spellbound?</i></br></br>Meine Hauptarbeit besteht in der Pressearbeit für Spellbound Entertainment. Ich verfasse Pressemitteilungen und halte den Kontakt zur Presse und Agenturen. Da diese Arbeit allein meinen Tag - noch - nicht vollständig ausfüllt, kümmere ich mich um die Community von Spellbound und schreibe und redigiere Handbücher, Dialogtexte und so weiter.</br></br></br>
<i>Du hast ja Spellbound Forum geschrieben, dass ihr den Gedanken von Robin Hood schon sehr lange habt. Spukte jetzt die Desperados oder die Robin Hood Idee länger in euren Köpfen herum?</i></br></br>Ganz klar Desperados. Die Idee zu Desperados kam, als Armin und Jean-Marc einen Western im Fernsehen sahen. Das ist inzwischen über 3 Jahre her. Die Idee zu Robin Hood wurde erst im Spätsommer 2001 "geboren".</br></br></br>
<i>Es ging ja einmal das Gerücht um, Desperados sei nur dazu da gewesen, um Programmiererfahrungen für Robin Hood zu sammeln. Ist da was dran?</i></br></br>Nein. Desperados war mehr als "nur" ein "Lernspiel" für unsere Programmierer. Darin steckt die volle Arbeitskraft eines ambitionierten Teams, das eines der besten Spiele für den PC erschaffen wollte - und damit Erfolg hatte. Natürlich sammelte das Spellbound-Team während der Entwicklung von Desperados Erfahrungen und setzt diese nun in Robin Hood um. Es wäre doch traurig, wenn Spellbound auf der Stelle treten würde und ständig dieselben Spiele ohne Neuerungen produzieren würde. Nicht?</br></br></br>
<i>Die Grafik-Engine von Robin Hood wird ja eine erweiterte Form der Desperados-Engine sein. Was habt ihr alles an ihr verändert?</i></br></br>Ein besseres Komprimierungsverfahren erlaubt es uns, die Bilddaten um das vierfache zu vergrößern. Dadurch konnten wir zum Beispiel die Animationsphasen der Charaktere verdoppeln und die Charaktere im Spiel etwa 25% größer gestalten. Das Ergebnis sind flüssigere Bewegungen und detailreichere Figuren.</br></br></br>
<i>Böse Zungen behaupten ja, dass die KI bei Desperados an manchen Stellen versagt hat. Habt ihr euch nun, speziell wegen dieser Aussage, besonders viel Mühe gegeben bei der KI von Robin Hood?</i></br></br>Auch eine natürliche Intelligenz versagt an einigen Stellen ;-). Die KI von Robin Hood ist fast von Grund auf neu geschrieben worden. Das war nötig um den NPCs neue Fähigkeiten beizubringen und den Kampf mit mittelalterlichen Waffen darstellen zu können. Die Schergen von Prinz John bewegen sich anders als die Gegner in Desperados. Sie teilen sich in defensive oder offensive Formationen auf und hören auf Befehle, die ihnen die Offiziere erteilen. Die Soldaten sind inzwischen sogar so intelligent, dass sie auch selbst entscheiden können, ob sie in einen Kampf eingreifen sollten - oder besser abwarten, um einem gepanzerten Ritter nicht ins Handwerk zu pfuschen.</br></br></br>
<i>In Robin Hood wird man ja den Schwierigkeitsgrad frei wählen können. Kann man vor jeder Mission neu wählen oder muss man sich am Anfang des Spieles entscheiden?</i></br></br>Vor und während des Spiels. Vor dem Spiel indem ihr eine der drei Einstellungen wählt. Während des Spiels könnt ihr euch bestimmte Missionen durch so genannte Vorbereitungsmissionen erheblich erleichtern. Wie das genau aussieht, soll eine Überraschung werden...</br></br></br>
<i>Inwiefern unterscheiden sich die Schwierigkeitsgrade und wieviele gibt es?</i></br></br>Es wird drei Schwierigkeitsgrade geben, wobei "normal" in etwa dem Schwierigkeitsgrad von Desperados entspricht. Unterscheiden werden sie sich hauptsächlich durch Veränderungen an den Charakter- Eigenschaften der NPCs.</br></br></br>
<i>Welche Waffen wird es in Robin Hood geben und wer der Charaktere kann diese nutzen?</i></br></br>Schwerter und Schilde, Äxte, Kampfstäbe, Bögen, Dolche, Morgensterne, Keulen, Speere, Hellebarden, Äpfel und Wespennester. Robin Hood wird mit Bogen, Stab und Schwert kämpfen ... und mehr wird (noch) nicht verraten ;-)</br></br></br>
<i>Auf den Screenshots ist in der linken oberen Ecke das britische Pfund-Zeichen zu sehen. Wird es in Robin Hood Geld geben und wie wird man es einsetzen können?</i></br></br>Eines der wichtigsten Ziele Robin Hoods war es, Richard Löwenherz aus der Gefangenschaft freizukaufen, damit dieser wieder seinen rechtmäßigen Thron in England besteigen konnte. Dafür brauchte er Unmengen Geld. Dass er also alles geklaute Geld den Armen zurückgab stimmt nur teilweise. Einen großen Teil sparte er für das Lösegeld seines Königs. Diese Aufgabe haben wir auch im Spiel übernommen.</br></br></br>
<i>Ebenfalls sieht man auf den Screenshots bei den Bildern der Charaktern die Bezeichnung "Merry Man B". Was hat das zu bedeuten?</i></br></br>Das ist einer von drei zusätzlichen, spielbaren Charakteren, die neben den Helden wie Robin Hood, Lady Marian, Bruder Tuck, Little John, etc. im Spiel auftauchen. Es wird insgesamt neun spielbare verschiedene Charaktere mit unterschiedlichen Fähigkeiten geben.</br></br></br>
<i>Wird man im neuen Spiel auch Waffen oder Ausrüstungsgegenstände zwischen den einzelnen Charakteren austauschen können, wie es in Commandos 2 der Fall war?</i></br></br>Nein, das haben wir nicht vor. Ihr könnt aber selbst entscheiden, welcher der neun Charaktere euch in der Mission unterstützt. Natürlich wird euch das Spiel eine Gruppenzusammenstellung vorschlagen - befolgen müsst Ihr sie aber nicht.</br></br></br>
<i>Ihr sagt dass ihr den Release- Termin 3. Quartal 2003 für sehr realistisch einschätzt - warum seid ihr euch da so sicher? Bei den meisten Spielen kommen doch eigentlich immer Verzögerungen vor.</i></br></br>Wir haben während der vergangenen Entwicklungen sehr viel Erfahrung gesammelt. Dadurch konnten wir den Entwicklungsprozess verbessern, um Robin Hood und zukünftige Projekte noch effizienter durchzuführen. Das gesamte Projekt ist durchgeplant und wir können jede leichte Abweichung sehr schnell meistern. Es sollte für uns ein Versuch sein, aber wir wissen jetzt schon, dass sich diese Strategie gelohnt hat!</br></br></br>
<i>Zum Schluss natürlich noch die obligatorische Frage: Kannst du uns schon etwas Neues über das Add-On (Webisodes) von Desperados oder über Airline Tycoon Evolution sagen?</i></br></br>Leider nein.</br></br></br>


