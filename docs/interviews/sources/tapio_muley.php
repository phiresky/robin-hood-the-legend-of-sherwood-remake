<b>robinhood-game.de:</b> <i>Könntest du Dich zu Beginn vielleicht ein bisschen vorstellen damit wir einen kleinen Eindruck von Dir erhalten? Wo liegen Deine Interessen? Was machst Du beruflich?</i></br></br>
<b>Tapio Muley:</b></br>
Mein Name ist Tapio Muley und man kennt mich im Internet unter dem Pseudonym "Shao-Lee". Ich bin 32 Jahre alt und komponiere schon seit über 13 Jahren Computer-Musik. Die elektronische Musik, insbesondere aus den 80er Jahren, hat mich schon sehr früh geprägt und lässt mich auch bis heute nicht mehr los. Durch meine (bis heute anhaltende) Begeisterung für Computerspiele war es für mich schon immer ein Traum gewesen, einmal den kompletten Soundtrack für solch ein Computerspiel zu schreiben.</br></br>
 
Mein tägliches Brot verdiene ich als Netzwerkadministrator. Hier betreue ich ein EDV-Netzwerk mit ca. 40 Arbeitsplätzen.</br></br>
 
Die Musik selbst ist ein intensives Hobby von mir, wobei der Ausdruck "Hobby" mittlerweile auch nicht mehr so ganz zutreffens ist ;) Aber meine Einstellung hat sich nicht verändert: Musik muss Spass machen - nicht nur für den Komponisten, sondern insbesondere auch für den Zuhörer !</br></br></br></br>


<b>robinhood-game.de:</b> <i>Arbeitest Du für irgendeine Firma oder bist du freischaffender Künstler?</i></br></br>
<b>Tapio Muley:</b></br>
Ich bin freiberuflich tätig, arbeite also selbstständig und unabhängig.</br></br></br></br></br>


<b>robinhood-game.de:</b> <i>Hast Du schon des öfteren für PC-Spiele komponiert und in welcher Weise warst Du an der Entstehung von Spellbound's Robin Hood beteiligt?</i></br></br>
<b>Tapio Muley:</b></br>
Musik für die Computerszene selbst mache ich schon seit jeher. Robin Hood war für mich jedoch angesichts des Umfanges und der Tatsache, dass dieses Spiel auch tatsächlich einmal den Weg in die Ladenregale finden wird, eine neue Herausforderung ! Meine Aufgaben bei Spellbound waren die Komposition der IN-Game-Musik sowie Arbeiten im Bereich der Soundeffekte von Robin Hood.</br></br></br></br>


<b>robinhood-game.de:</b> <i>Kannst Du uns etwas über die Zusammenarbeit mit der Firma Spellbound erzählen? Wie können wir uns die Zusammenarbeit vorstellen - wird alles per E-Mail abgewickelt oder warst Du auch vor Ort ? Wie bist Du eigentlich zur Firma Spellbound gekommen?</i></br></br>
<b>Tapio Muley:</b></br>
Man kann nur einen gewissen Teil über eMail abwickeln - beispielsweise Soundupdates verschicken oder einen kleineren Gedankenaustausch vollziehen. Gemeinsame Besprechungen sind insbesondere im Entwicklungsprozess unabdingbare Voraussetzungen für ein gutes Gesamtergebnis. Aus diesem Grund war ich auch selbst sehr oft bei der Firma Spellbound und wir haben uns dann gemeinsam über meine Ausarbeitungen unterhalten.</br>
An dieser Stelle möchte ich ausdrücklich die Zusammenarbeit mit der Firma Spellbound loben ! Für einen Musiker ist die Information zu einem Computerspiel das "A und O" ! All meine Fragen fanden immer ein offenes Ohr und das gemeinsame Ziel, Robin Hood, stand stets im Vordergrund.</br></br></br></br>


<b>robinhood-game.de:</b> <i>Hattest Du für jedes Stück eine feste Vorstellung oder hast Du während des Komponierens eher spontan gehandelt? Du hast ja schon früher erwähnt, dass Dir die Stimmung der einzelnen Musikstücke sehr am Herzen liegt. Wo hast Du Dir Deine Inspirationen geholt und woher wusstest du dass die Musik dann auch zum entsprechenden Level passt?</i></br></br>
<b>Tapio Muley:</b></br>
Wie bereits oben schon erwähnt, ist die Information zu einem Spiel das "A und O" für einen Komponisten. Man macht sich also zuerst grundsätzlich einmal Gedanken zum Gesamtthema, sprich: sollte die Musik zu "Robin Hood" eher Elemente aus der Filmmusik enthalten oder doch eher mittelalterliche Schwerpunkte setzen. Diese Frage haben wir gemeinsam (Spellbound und ich) sehr intensiv erörtert, da ja letztendlich hierin das Gesamtkonzept verborgen liegt. Wir haben uns für einen "Mittelweg" entschieden, welcher Elemente aus verschiedenen Musikgenres vereint. Wichtig war es, die Atmosphäre (Stimmung) von Robin Hood auch durch die Musik zu unterstreichen. Das lag mir persönlich auch sehr am Herzen.</br></br>
 
Wenn das Gesamtkonzept steht, geht es an die Ausarbeitung der einzelnen Level-musiken. Um meine Musik den Levels anzupassen, haben mir die tollen Umgebungsgrafiken als Leitfaden gedient. Das müsst Ihr Euch so vorstellen:</br>
Sämtliche Levels habe ich mir auf Din-A3 ausgedruckt. Die Bilder habe ich dann neben meinem Keyboard aufgestellt und mich dann von ihnen inspirieren lassen. Mein Ziel war es, die Stimmungen, die diese wunderschönen Grafiken vermitteln, auch in der Musik umzusetzen, um das Spielgefühl zu intensivieren. Jedem Level konnte ich somit auch musikalisch eine persönliche Note verleihen.</br></br></br></br>


<b>robinhood-game.de:</b> <i>Hast Du alle Deine Ideen umsetzen können und hast Du Deiner Meinung nach Dein Ziel erreicht?</i></br></br>
<b>Tapio Muley:</b></br>
Alle meine Ideen habe ich leider nicht umsetzen können. Das hatte verschiedene Gründe: zum einen waren die zeitlichen Terminsetzungen sehr eng, zum anderen gabs auch die eine oder andere technische Hürde zu nehmen. Hinter dem Ergebnis stehe ich aber trotzdem voll und ganz und bin auch ein bischen stolz darauf, dass ich das (auch mir persönlich) definierte Ziel erreichen konnte :-)</br></br></br></br>


<b>robinhood-game.de:</b> <i>Die Musikstücke, die wir bis jetzt gehört haben, klingen sehr professionell. Mit welchen Hilfsmitteln arbeitest Du?</i></br></br>
<b>Tapio Muley:</b></br>
Dankeschön !</br></br>
 
Grundsätzlich wird die Musik elektronisch erzeugt, d.h. mit elektronischen Klangerzeugern sowie einem PC. In meinem Fall sind das Synthesizer (elektronische Tasteninstrumente), ein Musikcomputer (PC), sowie Hardware für das Abmischen der Sounds sowie für die Aufnahme. Das Herzstück meiner Anlage stellt mit Sicherheit meine Workstation "Triton" von Korg dar, was ein äußerst inspirierender Synthesizer ist.</br></br></br></br>


<b>robinhood-game.de:</b> <i>Gibt es noch weitere Stücke von Dir im Internet (oder sogar im Handel) und wo könnten wir diese bekommen?</i></br></br>
<b>Tapio Muley:</b></br>
Es gibt in der Tat weitere Musikstücke von mir, aber leider nicht im Handel. Vielleicht ergibt sich aber einmal die Gelegenheit, auch für den "Stand-Alone"-Musikmarkt zu produzieren.</br>
Ich arbeite derzeit mit Hochdruck an der Fertigstellung meiner privaten Internetseite. In den nächsten Tagen ist es soweit, dann geht meine neue Webside "www.shao-lee.de" online. Dort werdet Ihr neben zahlreichen Informationen auch einige Soundtracks zum Download finden. Habt also noch ein bischen Geduld ;)</br></br></br></br>


<b>robinhood-game.de:</b> <i>Es gibt ja sehr viele junge Komponisten, die ebenfalls in dieses Buisness einsteigen wollen, um als Sounddesigner für professionelle Spiele zu arbeiten. Welche Vorraussetzungen müssen sie erfüllen und was kannst Du ihnen als Tipp mit auf den Weg geben?</i></br></br>
<b>Tapio Muley:</b></br>
Ganz wichtige Faktoren sind hier Eigeninitiative und Kreativität !</br></br>
Es gibt tatsächlich sehr viele junge Künster, die versuchen, in dieser Branche Fuß zu fassen und die auch professionell einsteigen wollen.</br></br>
Die Musikuntermalung in Computerspielen hat sich in den letzten Jahren jedoch sehr verändert. Waren es früher eher "Modul"-basierende Soundtracks, die aufwendig programmiert werden mussten, so gleichen heutige Kompositionsarbeiten eher den professionellen Musikproduktionen in der Film- und Fernsehindustrie. Um diesen Qualitätsstandard zu erreichen, sind nicht unerhebliche Investitionen erforderlich, da gutes Equipment sehr teuer ist. Bereits diese Hürde macht es für Einsteiger sehr schwierig.</br></br>
Ein unersetzbarer Faktor ist aber auch die Kreativität eines Musikers ! Um sein Können unter Beweis zu stellen, bieten sich beispielsweise Freewareprojekte an, die man im Internet zu Hauf findet. Das können MOD's (Modifications) oder auch kleinere Spiele sein. Wenn man dann auch mal den einen oder anderen Soundtrack auf diese Weise veröffentlicht hat, hat der Künstler nicht nur eine Refferenz, sondern auch die Chance, dass auf seine Musik auch professionelle Produktionsfirmen aufmerksam werden.</br>
Auch schadet es nie, einmal eine Demo-CD an hiesige Spieleschmieden zu senden. Solche Einsendungen landen mit Sicherheit nie ungehört im Mülleinmer. Wie bereits oben erwähnt: die Eigeninitiative ist hier auch ganz wichtig !</br></br>
Bitte berücksichtigt, dass dies meine persönlich gemachten Erfahrungen sind !</br></br></br></br>


<b>robinhood-game.de:</b> <i>Brennt Dir zum Schluss noch irgendwas auf der Zunge, dass Du unbedingt noch loswerden möchtest? Oder hast Du vielleicht eine kleine Schlussbemerkung?</i></br></br>
<b>Tapio Muley:</b></br>
Ich glaube, man kann sich kaum vorstellen, wieviel Arbeit und Kreativität in solch einem grossen Spieleprojekt steckt, wenn man den Entwicklungsprozess nicht selbst miterlebt hat.</br></br>
Für uns alle wünsche ich mir, dass Robin Hood die Erwartungen der Fans erfüllen wird und das Spiel den Erfolg erhält, den es dann auch verdient hat.</br></br></br></br></br>


<i>Wir bedanken uns für das aufschlussreiche Interview. Ich denke, dass die gesamte Robin Hood Community jetzt einen kleinen Eindruck gewonnen hat, wie die Musik entstanden ist und wie Spellbound und ihre Mitarbeiter sich untereinander austauschen.</br>Danke Tapio Muley!</i></br></br></br>


